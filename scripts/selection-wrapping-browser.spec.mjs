import { test, expect } from '@playwright/test';

test('selection wrappers share persistent settings across source and rich editing', async ({ page }) => {
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:43845');
  const rich = page.getByRole('textbox', { name: 'Markdown 文档编辑器', exact: true });
  await expect(rich).toBeVisible();
  await page.getByRole('button', { name: '切换源码模式', exact: true }).click();
  const source = page.getByRole('textbox', { name: 'Markdown 源码', exact: true });
  await source.click();
  await page.keyboard.press('ControlOrMeta+a');
  await page.keyboard.insertText('文字');
  await page.keyboard.press('ControlOrMeta+a');
  await page.keyboard.press('*');
  await expect(source).toHaveText('*文字*');
  await page.keyboard.press('*');
  await expect(source).toHaveText('**文字**');
  await page.keyboard.press('ControlOrMeta+a');
  await page.keyboard.insertText('文字');
  await page.getByRole('button', { name: '返回编辑', exact: true }).click();
  await expect(rich).toBeVisible();
  await rich.locator('p').filter({ hasText: '文字' }).click();
  await page.keyboard.press('Home');
  await page.keyboard.press('Shift+End');
  expect(await page.evaluate(() => window.getSelection()?.toString())).toBe('文字');
  await page.keyboard.press('*');
  await expect(rich.locator('[data-tano-live-inline-source]')).toHaveText('*文字*');
  expect(await page.evaluate(() => window.getSelection()?.toString())).toBe('文字');
  await page.keyboard.press('*');
  await expect(rich.locator('[data-tano-live-inline-source]')).toHaveText('**文字**');

  const openSettings = async () => {
    await page.getByRole('button', { name: /^切换上下文：/ }).click();
    await page.getByRole('button', { name: '设置', exact: true }).click();
    await page.getByRole('button', { name: '编辑设置', exact: true }).click();
  };
  await openSettings();
  await expect(rich.locator('strong')).toHaveText('文字');
  await page.getByRole('switch', { name: '高亮', exact: true }).click();
  await page.getByRole('switch', { name: '上标（扩展）', exact: true }).click();
  await expect(page.getByRole('switch', { name: '中文 ￥ 映射为 $', exact: true })).not.toBeChecked();
  await page.getByRole('switch', { name: '中文 ￥ 映射为 $', exact: true }).click();
  await page.getByRole('button', { name: '关闭设置', exact: true }).click();
  await page.reload();
  await expect(rich).toBeVisible();
  await openSettings();
  await expect(page.getByRole('switch', { name: '高亮', exact: true })).not.toBeChecked();
  await expect(page.getByRole('switch', { name: '上标（扩展）', exact: true })).toBeChecked();
  await expect(page.getByRole('switch', { name: '中文 ￥ 映射为 $', exact: true })).toBeChecked();
  await page.getByRole('button', { name: '关闭设置', exact: true }).click();
  await page.getByRole('button', { name: '切换源码模式', exact: true }).click();
  await source.click();
  await page.keyboard.press('ControlOrMeta+a');
  await page.keyboard.insertText('文字');
  await page.keyboard.press('ControlOrMeta+a');
  await page.keyboard.press('=');
  await expect(source).toHaveText('=');
  await page.keyboard.press('ControlOrMeta+a');
  await page.keyboard.insertText('文字');
  await page.keyboard.press('ControlOrMeta+a');
  await page.keyboard.press('^');
  await expect(source).toHaveText('^文字^');
  await page.keyboard.press('ControlOrMeta+a');
  await page.keyboard.insertText('x_1');
  await page.keyboard.press('ControlOrMeta+a');
  await page.keyboard.insertText('￥');
  await expect(source).toHaveText('$x_1$');
  await page.keyboard.press('ControlOrMeta+a');
  await page.keyboard.insertText('x_1');
  await page.getByRole('button', { name: '返回编辑', exact: true }).click();
  await rich.locator('p').filter({ hasText: 'x_1' }).click();
  await page.keyboard.press('Home');
  await page.keyboard.press('Shift+End');
  await page.keyboard.insertText('￥');
  await expect(rich.locator('[data-tano-live-inline-source]')).toContainText('$x_1$');
  await expect(rich.locator('.tano-live-math-preview')).toBeVisible();
  await page.getByRole('button', { name: '切换源码模式', exact: true }).click();
  await expect(source).toHaveText('$x_1$');
  expect(errors).toEqual([]);
});
