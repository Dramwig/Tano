import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { buildPlugin } from './plugin-build.mjs';

const { pkg } = await buildPlugin(resolve('examples/plugins/git-inspector'));
const target = resolve('packages/workbench/src/plugins/git-inspector.ts');
const content = `// Generated by npm run plugin:bundle. Edit examples/plugins/git-inspector instead.\nimport type { PluginPackage } from '@tano/protocol';\n\nexport const gitInspectorPlugin = ${JSON.stringify(pkg, null, 2)} satisfies PluginPackage;\n`;
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== content) throw new Error('Bundled Git inspector is stale. Run npm run plugin:bundle.');
  console.log('Bundled Git inspector matches its source.');
} else {
  await writeFile(target, content);
  console.log(`Bundled ${pkg.manifest.id} into ${target}`);
}
