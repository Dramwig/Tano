import { test, expect } from '@playwright/test';
import { readFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';

test('offline presentation plugin renders PPT and PPTX in the real sandbox and handles resize/zoom', async ({ page }) => {
  test.setTimeout(90000);
  const errors = [];
  page.on('pageerror', error => errors.push(String(error)));
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
  await page.goto('http://127.0.0.1:43845');
  await page.waitForFunction(() => document.querySelector('#app')?.__vue_app__?.config.globalProperties.$pinia?._s.get('workspace')?.workspace);
  expect(await page.title()).toBeTruthy();
  await expect.poll(() => page.evaluate(() => document.querySelector('#app').__vue_app__.config.globalProperties.$pinia._s.get('workspace').pluginRuntime.find(p => p.id === 'presentation-preview')?.status)).toBe('running');
  await page.evaluate(() => document.querySelector('#app').__vue_app__.config.globalProperties.$pinia._s.get('workspace').openPluginView('presentation-preview', 'slides'));
  const surface = page.locator('.plugin-surface[data-plugin="presentation-preview"]');
  const ui = surface.frameLocator('iframe[title="插件界面隔离容器"]').frameLocator('iframe[title="插件自定义界面"]');
  const toolbar = page.getByRole('toolbar', { name: '演示文稿预览操作' });
  await expect(toolbar).toBeVisible();
  const more = toolbar.getByRole('button', { name: '预览操作', exact: true });
  const menu = page.getByRole('dialog', { name: '预览操作', exact: true });
  const openMenu = async () => { if (!await menu.isVisible()) await more.click(); };
  const choose = async file => { await openMenu(); await menu.getByLabel('打开 PPT/PPTX').setInputFiles(file); };
  await expect(menu).toHaveCount(0);
  await expect(toolbar.getByRole('button')).toHaveCount(3);
  await more.focus(); await page.keyboard.press('ArrowDown');
  await expect(menu).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(menu).toHaveCount(0); await expect(more).toBeFocused();
  await expect(ui.locator('header')).toHaveCount(0);
  const network = [];
  page.on('request', request => { if (!request.url().startsWith('http://127.0.0.1:43845') && !/^(blob:|data:)/.test(request.url())) network.push(request.url()); });
  await expect(ui.locator('.preview-loading')).toBeHidden();
  await ui.locator('#app').evaluate(root => {
    window.previewLoadingPhases = [];
    new MutationObserver(() => {
      const text = root.querySelector('#status')?.textContent ?? '';
      if (text.startsWith('正在渲染')) window.previewLoadingPhases.push({ busy: root.getAttribute('aria-busy'), skeleton: !root.querySelector('.preview-loading').hidden });
    }).observe(root, { subtree: true, childList: true, attributes: true, attributeFilter: ['class', 'hidden'] });
  });
  mkdirSync(resolve('artifacts/presentation-preview'), { recursive: true });
  for (const extension of ['ppt', 'pptx']) {
    await choose(resolve(`scripts/fixtures/presentation-preview/fixture.${extension}`));
    await expect(ui.locator('#paper')).toContainText('Original layout test');
    await expect(ui.locator('#paper > svg')).toHaveAttribute('viewBox', '0 0 1280 720');
    await expect(toolbar.locator('.plugin-view-position')).toHaveText('1 / 1');
    const statusIcon = page.locator('.breadcrumb .document-status-trigger');
    await expect(statusIcon).toBeVisible();
    const fileBounds = await page.locator('.breadcrumb-current').boundingBox();
    const iconBounds = await statusIcon.boundingBox();
    expect(iconBounds.x).toBeGreaterThanOrEqual(fileBounds.x + fileBounds.width - 1);
    expect(Math.abs(iconBounds.y + iconBounds.height / 2 - fileBounds.y - fileBounds.height / 2)).toBeLessThan(4);
    await expect(ui.locator('footer')).toHaveCount(0);
    await statusIcon.hover();
    const infoPanel = page.locator('.document-status-panel');
    await expect(infoPanel).toContainText('不播放动画和视频');
    await infoPanel.hover(); await expect(infoPanel).toBeVisible();
    await page.keyboard.press('Escape'); await expect(infoPanel).toBeHidden();
    await statusIcon.focus(); await expect(infoPanel).toBeVisible();
    await page.keyboard.press('Escape'); await expect(infoPanel).toBeHidden();

    const text = ui.locator('#paper').getByText('Original layout test', { exact: true });
    await expect(text).toBeVisible();
    const style = await text.evaluate(element => ({ color: getComputedStyle(element).color, fontStyle: getComputedStyle(element).fontStyle }));
    expect(style.color).toBe('rgb(0, 128, 0)'); expect(style.fontStyle).toBe('italic');
    const breadcrumb = await page.locator('.breadcrumb').boundingBox();
    const controls = await toolbar.boundingBox();
    expect(Math.abs(controls.y + controls.height / 2 - breadcrumb.y - breadcrumb.height / 2)).toBeLessThan(3);
    expect(controls.x).toBeGreaterThan(breadcrumb.x + breadcrumb.width - 1);
    await openMenu();
    await menu.getByRole('button', { name: '开源许可' }).click();
    await expect(menu).toHaveCount(0);
    await expect(ui.locator('dialog')).toBeVisible();
    await ui.getByRole('button', { name: '关闭' }).click();
    const before = await ui.locator('#paper').boundingBox();
    await openMenu();
    await menu.getByRole('button', { name: '放大', exact: true }).click();
    expect((await ui.locator('#paper').boundingBox()).width).toBeGreaterThan(before.width);
    await menu.getByRole('button', { name: '适应宽度' }).click();
    await expect(menu).toBeVisible();
    await page.screenshot({ animations: 'disabled', path: resolve(`artifacts/presentation-preview/${extension}-menu-desktop.png`) });
    await page.keyboard.press('Escape');
    await expect(more).toBeFocused();
    await page.screenshot({ animations: 'disabled', path: resolve(`artifacts/presentation-preview/${extension}-desktop.png`) });
  }
  // Exercise the workspace -> authorized Worker -> chunked UI path, not just the file picker.
  await page.evaluate(async ({ bytes, runtimePath }) => {
    const app = document.querySelector('#app').__vue_app__;
    const store = app.config.globalProperties.$pinia._s.get('workspace');
    const { useWorkbenchRuntime } = await import(runtimePath);
    const runtime = app.runWithContext(() => useWorkbenchRuntime());
    runtime.attachments = { readAttachment: () => new Promise(resolve => { window.releasePreviewRead = () => resolve(new Uint8Array(bytes)); }) };
    await runtime.adapter.create('plugin-workspace.pptx', 'fixture');
    await store.refresh();
    void store.openAttachmentInNewTab(store.workspace.files.find(file => file.path === 'plugin-workspace.pptx'));
  }, { bytes: [...readFileSync(resolve('scripts/fixtures/presentation-preview/fixture.pptx'))], runtimePath: `/@fs/${resolve('packages/workbench/src/runtime.ts').replaceAll('\\', '/')}` });
  await expect(ui.locator('.preview-loading')).toBeVisible();
  await expect(ui.locator('#app')).toHaveAttribute('aria-busy', 'true');
  await expect(ui.locator('#paper')).toBeEmpty();
  const viewportBefore = page.viewportSize();
  await page.setViewportSize({ width: 1280, height: 720 });
  await page.screenshot({ animations: 'disabled', path: resolve('artifacts/presentation-preview/loading-desktop.png') });
  await page.locator('body').press('Control+b');
  await page.setViewportSize({ width: 390, height: 844 });
  const skeletonBounds = await ui.locator('.loading-paper').first().boundingBox();
  expect(skeletonBounds.x).toBeGreaterThanOrEqual(0);
  expect(skeletonBounds.x + skeletonBounds.width).toBeLessThanOrEqual(390);
  expect(skeletonBounds.width / skeletonBounds.height).toBeCloseTo(16 / 9, 2);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  expect(await ui.locator('.loading-title').first().evaluate(element => getComputedStyle(element).animationName)).toBe('none');
  await page.screenshot({ animations: 'disabled', path: resolve('artifacts/presentation-preview/loading-mobile.png') });
  const paintedSkeleton = await ui.locator('.loading-paper').first().boundingBox();
  expect(paintedSkeleton.width / paintedSkeleton.height).toBeCloseTo(16 / 9, 2);
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.setViewportSize(viewportBefore);
  await page.locator('body').press('Control+b');
  await page.evaluate(() => window.releasePreviewRead());
  await expect(ui.locator('.preview-loading')).toBeHidden();
  await expect(ui.locator('#app')).toHaveAttribute('aria-busy', 'false');
  expect(await ui.locator('#app').evaluate(() => window.previewLoadingPhases.some(phase => phase.busy === 'true' && phase.skeleton))).toBe(true);

  await expect(page.locator('.breadcrumb-current').filter({ hasText: 'plugin-workspace.pptx' })).toBeVisible();
  await expect(ui.getByRole('status')).toBeHidden();
  await expect(ui.locator('#paper')).toContainText('Original layout test');
  await choose(resolve('scripts/fixtures/presentation-preview/two-slides.pptx'));
  await expect(toolbar.locator('.plugin-view-position')).toHaveText('1 / 2');
  await toolbar.getByRole('button', { name: '下一页' }).click();
  await expect(ui.locator('#paper')).toContainText('Second slide');
  await expect(toolbar.locator('.plugin-view-position')).toHaveText('2 / 2');
  await ui.locator('main').focus(); await page.keyboard.press('ArrowLeft');
  await expect(ui.locator('#paper')).toContainText('Original layout test');
  await expect(page.locator('vite-error-overlay')).toHaveCount(0);
  await page.locator('body').press('Control+b');
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(ui.getByText('Original layout test', { exact: true })).toBeVisible();
  expect((await surface.boundingBox()).width).toBeGreaterThan(300);
  expect((await surface.boundingBox()).x).toBeLessThan(10);
  expect((await surface.boundingBox()).width).toBeLessThanOrEqual(390);
  const mobileControls = await toolbar.boundingBox();
  const mobileBreadcrumb = await page.locator('.breadcrumb').boundingBox();
  expect(mobileControls.x + mobileControls.width).toBeLessThanOrEqual(390);
  expect(Math.abs(mobileControls.y + mobileControls.height / 2 - mobileBreadcrumb.y - mobileBreadcrumb.height / 2)).toBeLessThan(3);
  await page.screenshot({ animations: 'disabled', path: resolve('artifacts/presentation-preview/pptx-mobile.png') });
  await openMenu();
  const menuBounds = await menu.boundingBox();
  expect(menuBounds.x).toBeGreaterThanOrEqual(0);
  expect(menuBounds.x + menuBounds.width).toBeLessThanOrEqual(390);
  await page.screenshot({ animations: 'disabled', path: resolve('artifacts/presentation-preview/pptx-menu-mobile.png') });
  await ui.locator('main').click({ position: { x: 12, y: 280 } });
  await expect(menu).toHaveCount(0);
  await choose({ name: 'broken.ppt', mimeType: 'application/vnd.ms-powerpoint', buffer: Buffer.from('invalid') });
  await expect(ui.getByRole('status')).toContainText('不是有效');
  await expect(ui.locator('.preview-loading')).toBeHidden();
  await expect(ui.locator('#app')).toHaveAttribute('aria-busy', 'false');
  await expect(ui.locator('#paper > svg')).toHaveCount(0);
  await page.evaluate(async () => {
    const store = document.querySelector('#app').__vue_app__.config.globalProperties.$pinia._s.get('workspace');
    await store.changePlugin({ id: 'presentation-preview', enabled: false }, store.workspace.id);
    await store.openAttachmentInNewTab(store.workspace.files.find(file => file.path === 'plugin-workspace.pptx'));
  });
  await expect(page.getByText('请在插件中启用系统插件「演示文稿预览」，然后重新打开文件。')).toBeVisible();
  await expect(surface.locator('iframe')).toHaveCount(0);
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#app')?.__vue_app__?.config.globalProperties.$pinia?._s.get('workspace')?.workspace);
  await expect.poll(() => page.evaluate(() => document.querySelector('#app').__vue_app__.config.globalProperties.$pinia._s.get('workspace').installedPlugins.find(p => p.manifest.id === 'presentation-preview')?.enabled)).toBe(false);
  await page.evaluate(async () => {
    const store = document.querySelector('#app').__vue_app__.config.globalProperties.$pinia._s.get('workspace');
    await store.changePlugin({ id: 'presentation-preview', enabled: true }, store.workspace.id);
  });
  await expect.poll(() => page.evaluate(() => document.querySelector('#app').__vue_app__.config.globalProperties.$pinia._s.get('workspace').pluginRuntime.find(p => p.id === 'presentation-preview')?.status)).toBe('running');
  expect(network).toEqual([]); expect(errors).toEqual([]);
});
