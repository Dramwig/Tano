function emojiIdentity(value: string) { return value.includes('\u200d') ? value : value.replace(/\ufe0f/g, ''); }
const curatedValues = new Set(curatedEmojiGroups.flatMap(group => group.icons.map(icon => emojiIdentity(icon.value))));
const metadataByValue = new Map(emojiCatalog.flatMap(group => group.icons.map(icon => [emojiIdentity(icon.value), icon] as const)));
/** Keep existing names and Unicode values while extending them with localized metadata. */
export const workspaceEmojiGroups: WorkspaceIconGroup[] = emojiCatalog.map(group => ({
  ...group,
  icons: [
    ...(curatedEmojiGroups.find(curated => curated.id === group.id)?.icons ?? []).map(icon => ({
      ...icon, keywords: `${icon.keywords} ${metadataByValue.get(emojiIdentity(icon.value))?.keywords ?? ''}`.trim(),
    })),
    ...group.icons.filter(icon => !curatedValues.has(emojiIdentity(icon.value))),
  ],
}));

