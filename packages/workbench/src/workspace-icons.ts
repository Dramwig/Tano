export function filterWorkspaceIconGroups(groups: WorkspaceIconGroup[], query: string, category = 'all') {
  const search = query.trim().toLocaleLowerCase();
  return groups
    .filter(group => search || category === 'all' || category === group.id)
    .map(group => ({
      ...group,
      icons: group.icons.filter(icon => !search || `${icon.label} ${icon.keywords} ${icon.value}`.toLocaleLowerCase().includes(search)),
    }))
    .filter(group => group.icons.length);
}
